function formatINRNum(num: number): string {
  return '₹' + Number(num || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function formatKgNum(num: number): string {
  return Number(num || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 }) + ' Kg';
}

function escapeXml(str: unknown): string {
  if (str === undefined || str === null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function randId(): string {
  return Math.floor(Math.random() * 0xffffff + 0x100000).toString(16).toUpperCase();
}

/**
 * Checks whether a given string is an auto-generated synthetic key.
 */
function isAutoGeneratedString(str?: string): boolean {
  if (!str) return false;
  const s = str.trim().toLowerCase();
  return (
    s.startsWith('sp-auto') ||
    s.startsWith('auto-') ||
    s.includes('auto uploaded') ||
    s.includes('autouploaded') ||
    s.includes('auto-uploaded') ||
    s.includes('auto-created') ||
    s === 'auto' ||
    s === 'recorded'
  );
}

/**
 * Normalizes text for matching species names.
 */
function normalizeSpeciesText(text?: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/^frozen\s+/i, '')
    .replace(/\[.*?\]/g, '')
    .replace(/\(.*?\)/g, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

/**
 * Robust matching between a transaction speciesId/remarks and a target species.
 */
export function matchesFishSpecies(
  rawSpeciesId?: string,
  targetSpeciesId?: string,
  targetSpecies?: Species | SpeciesHead,
  itemRemarks?: string,
  allKnownSpecies: Species[] = []
): boolean {
  if (!targetSpeciesId || targetSpeciesId === 'ALL') return true;
  if (!rawSpeciesId && !itemRemarks) return false;

  const rawClean = (rawSpeciesId || '').trim();
  const targetClean = targetSpeciesId.trim();

  // 1. Exact ID equality
  if (rawClean && rawClean.toLowerCase() === targetClean.toLowerCase()) return true;

  // 2. Check target code or name
  const targetName = targetSpecies?.name || '';
  const targetCode = targetSpecies?.code || '';
  const targetRaw = (targetSpecies as Species)?.rawSpeciesName || '';

  if (targetCode && rawClean.toLowerCase() === targetCode.toLowerCase()) return true;
  if (targetName && rawClean.toLowerCase() === targetName.toLowerCase()) return true;
  if (targetRaw && rawClean.toLowerCase() === targetRaw.toLowerCase()) return true;

  // 3. Normalized string matching
  const normRaw = normalizeSpeciesText(rawClean);
  const normTarget = normalizeSpeciesText(targetName || targetClean);
  const normTargetRaw = normalizeSpeciesText(targetRaw);

  if (normTarget && normRaw === normTarget) return true;
  if (normTargetRaw && normRaw === normTargetRaw) return true;

  // 4. If raw is an auto key, inspect remarks
  if (itemRemarks && isAutoGeneratedString(rawClean)) {
    const normRemarks = normalizeSpeciesText(itemRemarks);
    if (normTarget && (normRemarks.includes(normTarget) || normTarget.includes(normRemarks))) return true;
    if (normTargetRaw && (normRemarks.includes(normTargetRaw) || normTargetRaw.includes(normRemarks))) return true;
  }

  // 5. Look up rawSpeciesId in all known species
  const matchedInList = allKnownSpecies.find(
    (s) =>
      s.id.toLowerCase() === rawClean.toLowerCase() ||
      s.code.toLowerCase() === rawClean.toLowerCase() ||
      s.name.toLowerCase() === rawClean.toLowerCase() ||
      (s.rawSpeciesName && s.rawSpeciesName.toLowerCase() === rawClean.toLowerCase())
  );

  if (matchedInList) {
    if (matchedInList.id.toLowerCase() === targetClean.toLowerCase()) return true;
    if (targetCode && matchedInList.code.toLowerCase() === targetCode.toLowerCase()) return true;
    const normMatched = normalizeSpeciesText(matchedInList.rawSpeciesName || matchedInList.name);
    if (normTarget && normMatched === normTarget) return true;
  }

  return false;
}

/**
 * Builds a chronological Fish-wise (Species) Ledger Statement with opening balance,
 * running weights, running landed costs, and average landed rates.
 */
export function buildFishwiseLedgerStatement(
  params: BuildFishwiseLedgerParams
): FishwiseLedgerStatementResult {
  const {
    speciesId,
    selectedSpecies,
    purchases,
    purchaseReturns = [],
    suppliers = [],
    locations = [],
    grades = [],
    sizes = [],
    counts = [],
    speciesList = [],
    purchaseSpeciesList = [],
    startDate,
    endDate
  } = params;

  const targetId = speciesId || selectedSpecies?.id || 'ALL';
  const allSpeciesCombined = [...purchaseSpeciesList, ...speciesList];

  const supplierMap = new Map(suppliers.map((s) => [s.id, s]));
  const locationMap = new Map(locations.map((l) => [l.id, l]));
  const gradeMap = new Map(grades.map((g) => [g.id, g]));
  const sizeMap = new Map(sizes.map((s) => [s.id, s]));
  const countMap = new Map(counts.map((c) => [c.id, c]));

  // Filter purchases for target species (excluding voided)
  const matchedPurchases = purchases.filter((p) => {
    if (p.isVoided) return false;
    if (targetId === 'ALL') return true;
    return matchesFishSpecies(p.speciesId, targetId, selectedSpecies, p.remarks, allSpeciesCombined);
  });

  // Filter purchase returns for target species (excluding voided)
  const matchedReturns = purchaseReturns.filter((ret) => {
    if (ret.isVoided) return false;
    if (targetId === 'ALL') return true;
    return matchesFishSpecies(ret.speciesId, targetId, selectedSpecies, ret.detailedReason, allSpeciesCombined);
  });

  interface RawFishEvent {
    id: string;
    date: string;
    type: 'PURCHASE' | 'RETURN';
    voucherRef: string;
    invoiceNo: string;
    supplierName: string;
    locationName: string;
    grade: string;
    sizeCount: string;
    boxesCount: number | null;
    inwardWeightKg: number | null;
    outwardWeightKg: number | null;
    purchaseRatePerKg: number | null;
    expenseRatePerKg: number | null;
    purchaseValue: number | null;
    damageAmount: number | null;
    expenseValue: number | null;
    landedCost: number;
    returnCredit: number;
    effectiveRatePerKg: number | null;
    briefDetails: string;
  }

  const rawEvents: RawFishEvent[] = [];

  matchedPurchases.forEach((p) => {
    const weightKg = Number(p.weightKg || 0);
    const ratePerKg = Number(p.ratePerKg || 0);
    const rawPurchaseVal = p.purchaseValue !== undefined ? Number(p.purchaseValue) : Number((weightKg * ratePerKg).toFixed(2));
    const damageAmt = Number(p.damageAmount || 0);
    const netPurchaseValue =
      p.grossPurchaseValue !== undefined
        ? Number(p.grossPurchaseValue)
        : Number(Math.max(0, rawPurchaseVal - damageAmt).toFixed(2));
    const expenseValNum = Number(p.totalExpenses || 0);
    const hasExpense = expenseValNum > 0;
    const expenseRate = hasExpense && weightKg > 0 ? Number((expenseValNum / weightKg).toFixed(2)) : null;
    const landedCost =
      p.totalCost !== undefined
        ? Number(p.totalCost)
        : Number((netPurchaseValue + expenseValNum).toFixed(2));
    const effRate = weightKg > 0 ? Number((landedCost / weightKg).toFixed(2)) : null;

    const supp = supplierMap.get(p.supplierId);
    const suppName = supp ? `${supp.name} (${supp.code})` : 'Supplier';
    const loc = locationMap.get(p.locationId);
    const locName = loc ? loc.name : 'Harbour Wharf';
    const grd = gradeMap.get(p.gradeId);
    const sz = sizeMap.get(p.sizeId);
    const cnt = countMap.get(p.countId);

    const specParts: string[] = [];
    if (sz?.name) specParts.push(sz.name);
    if (cnt?.name) specParts.push(`Count ${cnt.name}`);
    const sizeCount = specParts.join(' · ') || 'Standard';

    const detailParts: string[] = [];
    if (p.invoiceNo) detailParts.push(`Inv: ${p.invoiceNo}`);
    if (damageAmt > 0) detailParts.push(`Damage -₹${damageAmt}`);
    if (p.remarks && !isAutoGeneratedString(p.remarks)) detailParts.push(p.remarks);
    const briefDetails = detailParts.join(' · ') || 'Catch Landed';

    rawEvents.push({
      id: `pur-${p.id}`,
      date: p.purchaseDate,
      type: 'PURCHASE',
      voucherRef: p.purchaseId,
      invoiceNo: p.invoiceNo || '',
      supplierName: suppName,
      locationName: locName,
      grade: grd?.name || 'A Grade',
      sizeCount,
      boxesCount: p.boxesCount || null,
      inwardWeightKg: weightKg,
      outwardWeightKg: null,
      purchaseRatePerKg: ratePerKg,
      expenseRatePerKg: expenseRate,
      purchaseValue: netPurchaseValue,
      damageAmount: damageAmt > 0 ? damageAmt : null,
      expenseValue: hasExpense ? Number(expenseValNum.toFixed(2)) : null,
      landedCost,
      returnCredit: 0,
      effectiveRatePerKg: effRate,
      briefDetails
    });
  });

  matchedReturns.forEach((ret) => {
    const supp = ret.supplierId ? supplierMap.get(ret.supplierId) : undefined;
    const suppName = supp ? `${supp.name} (${supp.code})` : 'Supplier';
    const grd = ret.gradeId ? gradeMap.get(ret.gradeId) : undefined;
    const sz = ret.sizeId ? sizeMap.get(ret.sizeId) : undefined;
    const cnt = ret.countId ? countMap.get(ret.countId) : undefined;

    const specParts: string[] = [];
    if (sz?.name) specParts.push(sz.name);
    if (cnt?.name) specParts.push(`Count ${cnt.name}`);
    const sizeCount = specParts.join(' · ') || 'Standard';

    const linkedRef = ret.purchaseRefNo ? `Ref: ${ret.purchaseRefNo}` : '';
    const reasonText = ret.reason ? ret.reason : 'Rejection';
    const brief = [reasonText, ret.detailedReason, linkedRef].filter(Boolean).join(' · ');

    rawEvents.push({
      id: `ret-${ret.id}`,
      date: ret.returnDate,
      type: 'RETURN',
      voucherRef: ret.returnNo,
      invoiceNo: ret.invoiceNo || '',
      supplierName: suppName,
      locationName: 'Rejection / Return',
      grade: grd?.name || 'Rejection',
      sizeCount,
      boxesCount: ret.boxesCount || null,
      inwardWeightKg: null,
      outwardWeightKg: Number(ret.returnedWeightKg || 0),
      purchaseRatePerKg: Number(ret.ratePerKg || 0),
      expenseRatePerKg: null,
      purchaseValue: null,
      damageAmount: null,
      expenseValue: null,
      landedCost: 0,
      returnCredit: Number(ret.returnedValue || 0),
      effectiveRatePerKg: Number(ret.ratePerKg || 0),
      briefDetails: brief
    });
  });

  // Sort chronologically by date; on same date show purchases before returns
  const typeRank: Record<RawFishEvent['type'], number> = { PURCHASE: 0, RETURN: 1 };
  rawEvents.sort((a, b) => {
    const diff = new Date(a.date).getTime() - new Date(b.date).getTime();
    if (diff !== 0) return diff;
    return typeRank[a.type] - typeRank[b.type];
  });

  // Calculate opening balance for events prior to startDate (if startDate provided)
  let openingWeightKg = 0;
  let openingCost = 0;

  if (startDate) {
    rawEvents.forEach((e) => {
      if (e.date < startDate) {
        if (e.type === 'PURCHASE') {
          openingWeightKg += e.inwardWeightKg || 0;
          openingCost += e.landedCost;
        } else if (e.type === 'RETURN') {
          openingWeightKg -= e.outwardWeightKg || 0;
          openingCost -= e.returnCredit;
        }
      }
    });
  }

  openingWeightKg = Number(openingWeightKg.toFixed(2));
  openingCost = Number(openingCost.toFixed(2));
  const openingAvgRate = openingWeightKg > 0 ? Number((openingCost / openingWeightKg).toFixed(2)) : 0;

  // Filter events within date window
  const filteredEvents = rawEvents.filter((e) => {
    if (startDate && e.date < startDate) return false;
    if (endDate && e.date > endDate) return false;
    return true;
  });

  let runningWeight = openingWeightKg;
  let runningCost = openingCost;

  const rows: FishwiseLedgerStatementRow[] = filteredEvents.map((e, idx) => {
    const signedWeight = (e.inwardWeightKg || 0) - (e.outwardWeightKg || 0);
    runningWeight = runningWeight + signedWeight;
    runningCost = runningCost + e.landedCost - e.returnCredit;
    const runningAvg = runningWeight > 0 ? Number((runningCost / runningWeight).toFixed(2)) : 0;

    return {
      id: `fish-led-${idx}`,
      date: e.date,
      formattedDate: formatDDMMYYYY(e.date) || e.date,
      type: e.type,
      voucherRef: e.voucherRef,
      invoiceNo: e.invoiceNo,
      supplierName: e.supplierName,
      locationName: e.locationName,
      grade: e.grade,
      sizeCount: e.sizeCount,
      boxesCount: e.boxesCount,
      inwardWeightKg: e.inwardWeightKg,
      outwardWeightKg: e.outwardWeightKg,
      netWeightKg: signedWeight,
      purchaseRatePerKg: e.purchaseRatePerKg,
      expenseRatePerKg: e.expenseRatePerKg,
      purchaseValue: e.purchaseValue,
      damageAmount: e.damageAmount,
      expenseValue: e.expenseValue,
      landedCost: Number(e.landedCost.toFixed(2)),
      returnCredit: Number(e.returnCredit.toFixed(2)),
      effectiveRatePerKg: e.effectiveRatePerKg,
      runningWeightKg: Number(runningWeight.toFixed(2)),
      runningLandedCost: Number(runningCost.toFixed(2)),
      runningAvgRatePerKg: runningAvg,
      briefDetails: e.briefDetails
    };
  });

  const totalInwardWeightKg = Number(rows.reduce((s, r) => s + (r.inwardWeightKg || 0), 0).toFixed(2));
  const totalOutwardWeightKg = Number(rows.reduce((s, r) => s + (r.outwardWeightKg || 0), 0).toFixed(2));
  const netTotalWeightKg = Number((totalInwardWeightKg - totalOutwardWeightKg).toFixed(2));
  const totalPurchaseValue = Number(rows.reduce((s, r) => s + (r.purchaseValue || 0), 0).toFixed(2));
  const totalExpenseValue = Number(rows.reduce((s, r) => s + (r.expenseValue || 0), 0).toFixed(2));
  const totalDamageAmount = Number(rows.reduce((s, r) => s + (r.damageAmount || 0), 0).toFixed(2));
  const totalDebits = Number(rows.reduce((s, r) => s + r.landedCost, 0).toFixed(2));
  const totalCredits = Number(rows.reduce((s, r) => s + r.returnCredit, 0).toFixed(2));
  const closingWeightKg = Number((openingWeightKg + netTotalWeightKg).toFixed(2));
  const closingCost = Number((openingCost + totalDebits - totalCredits).toFixed(2));
  const weightedAvgPurchaseRate = totalInwardWeightKg > 0 ? Number((totalPurchaseValue / totalInwardWeightKg).toFixed(2)) : 0;
  const weightedAvgLandedRate = totalInwardWeightKg > 0 ? Number((totalDebits / totalInwardWeightKg).toFixed(2)) : 0;
  const totalLotsCount = rows.length;

  return {
    rows,
    openingWeightKg,
    openingCost,
    openingAvgRate,
    totalInwardWeightKg,
    totalOutwardWeightKg,
    netTotalWeightKg,
    totalPurchaseValue,
    totalExpenseValue,
    totalDamageAmount,
    totalDebits,
    totalCredits,
    closingWeightKg,
    closingCost,
    weightedAvgPurchaseRate,
    weightedAvgLandedRate,
    totalLotsCount
  };
}

